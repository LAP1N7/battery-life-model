def md_table(df):
    """minimal markdown table (pandas.to_markdown needs tabulate, not in the allowed package list)"""
    d = df.reset_index()
    cols = [str(c) if not isinstance(c, tuple) else "_".join(map(str, c)) for c in d.columns]
    L = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in d.iterrows():
        L.append("| " + " | ".join("" if (isinstance(v, float) and np.isnan(v)) else str(v) for v in r.values) + " |")
    return "\n".join(L)

OUT_DEFAULT = os.path.join(HERE, "out", "D")
