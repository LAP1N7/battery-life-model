PROTO_CSV = os.path.join(HERE, "..", "..", "prototype", "results", "mohtat", "rpt_feature_table.csv")   # read-only comparison input


def log(*a):
    print(time.strftime("%H:%M:%S"), *a, flush=True)


def order_columns(df):
    rest = [c for c in df.columns if c not in FIXED_COLS]
    return df[[c for c in FIXED_COLS if c in df.columns] + rest]


def pick_fig_cells(meta, cells_present):
    pick = []
    if meta is not None and "T_group" in meta.columns:
        for g in ("R", "C", "H"):
            m = meta[(meta["T_group"] == g) & meta["cell"].isin(cells_present)]
            if len(m):
                pick.append(m["cell"].iloc[0])
    return pick or cells_present[:3]


def make_figures(rows_by_cell, df, ocp, cfg, cells, outdir, meta):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from scipy import signal
    tg = meta.set_index("cell")["T_group"].to_dict() if meta is not None and "T_group" in meta.columns else {}
    for cell in cells:
        rows = [r for r in rows_by_cell[cell] if r["fit"] is not None and r["fit"].success and r["kind"] == "avg"]
        if len(rows) < 2:
            continue
        pick = [rows[0], rows[len(rows) // 2], rows[-1]]
        fig, ax = plt.subplots(3, 3, figsize=(13, 9), sharex="col")
        d = df[df["cell"] == cell].set_index("checkup_idx")
        for j, r in enumerate(pick):
            cv, f = r["curve"], r["fit"]
            s, V = cv["s"], cv["V"]
            Vm = dc.model_V(f.p, s, ocp)
            res = (Vm - V) * 1e3
            ds_ = s[1] - s[0]
            w = 31
            dV = signal.savgol_filter(V, w, 3, deriv=1, delta=ds_)
            dVm = signal.savgol_filter(Vm, w, 3, deriv=1, delta=ds_)
            row = d.loc[r["checkup_idx"]]
            ax[0, j].plot(s, V, "k.", ms=3, label="averaged C/20 data")
            ax[0, j].plot(s, Vm, "r-", lw=1.2, label="model")
            ax[0, j].set_title(f"cell {cell} ({tg.get(cell, '?')}), check-up {r['checkup_idx']}, {r['ah']:.0f} Ah\n"
                               f"RMSE {f.rmse_mV:.2f} mV  LLI {100*row['LLI']:.1f}  LAM_PE {100*row['LAM_PE']:.1f}  LAM_NE {100*row['LAM_NE']:.1f} %", fontsize=9)
            ax[1, j].plot(s, res, "b-")
            ax[1, j].axhline(0, color="gray", lw=0.5)
            ax[2, j].plot(s, -dV, "k-", lw=1.5, label="data")
            ax[2, j].plot(s, -dVm, "r--", lw=1.2, label="model")
            ax[2, j].set_xlabel("capacity below full state s [Ah]")
        ax[0, 0].set_ylabel("V [V]  (avg of chg/dis)")
        ax[1, 0].set_ylabel("model - data [mV]")
        ax[2, 0].set_ylabel("-dV/ds [V/Ah]")
        ax[0, 0].legend(fontsize=8)
        ax[2, 0].legend(fontsize=8)
        fig.tight_layout()
        p = os.path.join(outdir, f"D1_fit_cell{cell}.png")
        fig.savefig(p, dpi=110)
        plt.close(fig)
        log("figure", p)


def summarize(df, meta, outdir, proto_cmp, sens_notes, args, cfg, ocp):
    L = []
    P = L.append
    P("# D1 summary (auto-generated by stepD1_dva.py)\n")
    P(f"dataset `{args.dataset}`, OCP pair `{ocp.name}` ({ocp.source}), fit window {cfg.fit_vlo}-{cfg.fit_vhi} V, "
      f"averaged C/20 charge+discharge top-aligned, {cfg.n_starts} random + warm starts per check-up ({cfg.n_starts_ref} for the first fit of a cell).\n")
    tg = meta.set_index("cell")["T_group"].to_dict() if meta is not None and "T_group" in meta.columns else {}
    df = df.copy()
    df["T_group"] = df["cell"].map(tg)
    fit = df[df["rmse_mV"].notna()]
    ref = fit[fit["is_ref"]]
    P("## 1. OCP fitness (reference check-up RMSE)\n")
    P(f"n cells {ref['cell'].nunique()}; reference RMSE median {ref['rmse_mV'].median():.2f} mV, max {ref['rmse_mV'].max():.2f} mV; "
      f"cells above 10 mV: {int((ref['rmse_mV'] >= 10).sum())}.\n")
    P(md_table(ref.groupby("T_group")["rmse_mV"].agg(["count", "median", "max"]).round(2)) + "\n")
    P("## 2. Completion criteria per check-up (reference check-ups excluded)\n")
    nr = fit[~fit["is_ref"]]
    ev = nr[nr["cap_evaluable"]]
    P(f"check-ups {len(nr)}; fit RMSE < 10 mV: {int(nr['pass_rmse'].sum())}/{len(nr)} ({100*nr['pass_rmse'].mean():.1f} %).  "
      f"Capacity within 1 pp: {int(ev['pass_cap'].sum())}/{len(ev)} evaluable ({100*ev['pass_cap'].mean():.1f} %; "
      f"{len(nr)-len(ev)} not evaluable, no C/20 discharge).  Both: {int((ev['pass_rmse'] & ev['pass_cap']).sum())}/{len(ev)}.\n")
    P(f"|loss_implied - loss_meas|, pp: median {ev['loss_gap_pp'].abs().median():.2f}, 95th pct {ev['loss_gap_pp'].abs().quantile(.95):.2f}, max {ev['loss_gap_pp'].abs().max():.2f}.\n")
    pc = nr.groupby("cell").apply(lambda g: pd.Series(dict(
        n=len(g), rmse_pass=int(g["pass_rmse"].sum()), cap_pass=int(g[g["cap_evaluable"]]["pass_cap"].sum()),
        cap_eval=int(g["cap_evaluable"].sum()), rmse_max=g["rmse_mV"].max(), gap_max_pp=g["loss_gap_pp"].abs().max())), include_groups=False)
    pc["T_group"] = pc.index.map(tg)
    P("Per cell (n = check-ups after the reference):\n")
    P(md_table(pc.round(2)) + "\n")
    P("Cells with every check-up passing both criteria: "
      f"{int(((pc['rmse_pass'] == pc['n']) & (pc['cap_pass'] == pc['cap_eval'])).sum())}/{len(pc)}.\n")
    P("## 3. Mode ranges by temperature group\n")
    for lab, fn in (("at 10 % measured capacity loss (linear interpolation, reference = first averaged check-up)", "m10"), ("at the last check-up", "last")):
        P(f"### {lab}\n")
        rows = []
        for cell, g in fit.groupby("cell"):
            g = g.sort_values("ah")
            if fn == "m10":
                vals = {k: dp.matched_value(g, k, 0.10)[0] for k in ("LLI", "LAM_PE", "LAM_NE")}
                how = dp.matched_value(g, "LLI", 0.10)[1]
            else:
                vals = {k: g[k].iloc[-1] for k in ("LLI", "LAM_PE", "LAM_NE")}
                how = "last"
            rows.append(dict(cell=cell, T_group=tg.get(cell), how=how, **{k: 100 * v for k, v in vals.items()}))
        t = pd.DataFrame(rows)
        agg = t.groupby("T_group")[["LLI", "LAM_PE", "LAM_NE"]].agg(["min", "median", "max"]).round(1)
        P(md_table(agg) + "\n")
        if fn == "m10":
            P(f"cells where 10 % was not reached (last check-up used): {int((t['how'] == 'last_not_reached').sum())}; not evaluable: {int((t['how'] == 'na').sum())}\n")
            t.round(2).to_csv(os.path.join(outdir, "D1_modes_at_10pct.csv"), index=False)
    P("## 4. Flags and identifiability\n")
    P(f"check-ups with curve type not 'avg' (single-branch fallback): {int(fit['flag_curve_not_avg'].sum())}; "
      f"parameter at bound: {int(fit['flag_at_bound'].sum())}; multimodal (converged-start spread > 1 pp): {int(fit['flag_multimodal'].sum())}; "
      f"no empty state found: {int(fit['flag_no_empty_state'].sum())}; reference not BOL (cells): {int(ref['flag_ref_not_bol'].sum())}.\n")
    P(f"median Jacobian sd (percent of value): Cp {fit['sd_Cp_pct'].median():.2f}, Cn {fit['sd_Cn_pct'].median():.2f}, n_Li {fit['sd_nLi_pct'].median():.2f}; "
      f"median multistart spread (pp): LLI {fit['spread_LLI_pp'].median():.2f}, LAM_PE {fit['spread_LAM_PE_pp'].median():.2f}, LAM_NE {fit['spread_LAM_NE_pp'].median():.2f}; "
      f"median corr(Cp, Cn) {fit['corr_Cp_Cn'].median():.2f}.\n")
    if proto_cmp is not None:
        P("## 5. Comparison with the earlier exploratory Python results (prototype)\n")
        P(proto_cmp + "\n")
    if sens_notes:
        P("## 6. Sensitivities\n")
        P(sens_notes + "\n")
    with open(os.path.join(outdir, "D1_summary.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))


def compare_prototype(df_main, df_chg):
    """Compare with prototype rpt_feature_table.csv (columns cell, rpt, LLI_chg, LAM_NE_chg, LAM_PE_chg, rms_chg)."""
    if not os.path.exists(PROTO_CSV):
        return None
    pr = pd.read_csv(PROTO_CSV, dtype={"cell": str})
    pr = pr[["cell", "rpt", "cycle", "thr", "LLI_chg", "LAM_NE_chg", "LAM_PE_chg", "rms_chg", "T"]].rename(columns={"rpt": "checkup_idx"})
    lines = []
    for name, d, note in (("main (averaged branches, ref = first averaged check-up)", df_main, "H cells: reference differs (prototype uses charge-only BOL)"),
                          ("charge-only variant of this code (ref = BOL charge fit)", df_chg, "same reference check-up as prototype; differences = alignment/window/multistart")):
        m = d.merge(pr, on=["cell", "checkup_idx"], how="inner")
        m = m[m["rmse_mV"].notna() & m["LLI_chg"].notna()]
        for grp, mm in (("R+C cells", m[m["T"] != "H"]), ("H cells", m[m["T"] == "H"])):
            mm = mm[mm["ah"] > 0]
            if not len(mm):
                continue
            dl_ = 100 * (mm["LLI"] - mm["LLI_chg"])
            dn_ = 100 * (mm["LAM_NE"] - mm["LAM_NE_chg"])
            dp_ = 100 * (mm["LAM_PE"] - mm["LAM_PE_chg"])
            lines.append(f"- {name}, {grp} (n={len(mm)} check-ups after BOL): median(new - proto) LLI {dl_.median():+.1f} pp (|diff| 90th pct {dl_.abs().quantile(.9):.1f}), "
                         f"LAM_NE {dn_.median():+.1f} (|90th| {dn_.abs().quantile(.9):.1f}), LAM_PE {dp_.median():+.1f} (|90th| {dp_.abs().quantile(.9):.1f}); "
                         f"Spearman(new, proto): LLI {mm['LLI'].corr(mm['LLI_chg'], method='spearman'):.3f}, LAM_NE {mm['LAM_NE'].corr(mm['LAM_NE_chg'], method='spearman'):.3f}, "
                         f"LAM_PE {mm['LAM_PE'].corr(mm['LAM_PE_chg'], method='spearman'):.3f}.  ({note})")
    # last-check-up comparison for the main run
    mm = df_main.merge(pr, on=["cell", "checkup_idx"], how="inner")
    last = mm.sort_values("ah").groupby("cell").tail(1)
    last = last[last["LLI_chg"].notna() & last["LLI"].notna()]
    lines.append(f"- last check-up per cell, main vs prototype (n={len(last)}): median LLI {100*last['LLI'].median():.1f} vs {100*last['LLI_chg'].median():.1f} %, "
                 f"LAM_NE {100*last['LAM_NE'].median():.1f} vs {100*last['LAM_NE_chg'].median():.1f} %, LAM_PE {100*last['LAM_PE'].median():.1f} vs {100*last['LAM_PE_chg'].median():.1f} % (medians over cells, new vs prototype).")
    lines.append(f"- fit RMSE (median over check-ups): new main {df_main['rmse_mV'].median():.2f} mV (averaged curve, window 3.30-4.18 V) vs prototype charge fit {pr['rms_chg'].median():.2f} mV (full curve, includes fitted R); the two are not the same quantity.")
    return "\n".join(lines)


def check_team_c20(df, args):
    """Compare ah / soh with the team's out/c20.csv (common.load_c20 convention) when it exists (Mohtat only)."""
    f = os.path.join(HERE, "out", "c20.csv")
    if args.dataset != "mohtat" or not os.path.exists(f):
        return ""
    c = pd.read_csv(f)
    c["cell"] = c["cell"].map(lambda v: f"{int(v):02d}")
    c["soh_team"] = c.groupby("cell")["cap"].transform(lambda s: s / s.iloc[0])
    mine = df[df["cap_dis_meas"].notna()][["cell", "ah", "soh", "cap_dis_meas", "ref_checkup_idx", "flag_ref_not_bol"]]
    cells = set(df["cell"])
    c = c[c["cell"].isin(cells)]
    c["key"] = c["cell"] + "_" + c["ah"].round(3).astype(str)
    mine = mine.assign(key=mine["cell"] + "_" + mine["ah"].round(3).astype(str))
    both = mine.merge(c[["key", "cap", "soh_team"]], on="key", how="outer", indicator=True)
    only_me = both[both["_merge"] == "left_only"]
    only_t = both[both["_merge"] == "right_only"]
    m = both[both["_merge"] == "both"]
    # soh differs when the reference check-up differs (team: first check-up with both branches >=500 samples)
    d = (m["soh"] - m["soh_team"]).abs()
    lines = [f"- alignment with team out/c20.csv: {len(m)} check-ups matched on (cell, ah); only in D1 {len(only_me)}, only in c20.csv {len(only_t)}; "
             f"max |cap_D1 - cap_c20| {(m['cap_dis_meas'] - m['cap']).abs().max():.2e} Ah; max |soh_D1 - soh_c20| {d.max():.2e} (median {d.median():.2e}).",
             "  (soh column = capacity / first check-up that has both C/20 branches, the team convention; loss_meas for criterion C2 is relative to the mode reference instead)"]
    if len(only_me):
        lines.append("  only in D1: " + ", ".join(only_me["key"].head(10)))
    if len(only_t):
        lines.append("  only in c20.csv: " + ", ".join(only_t["key"].head(10)))
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", default="mohtat", help="built-in loader name or label when --loader-spec is used")
    ap.add_argument("--loader-spec", default=None, help="path.py:function of an external loader (YOUR code; not for downloaded folders)")
    ap.add_argument("--data-dir", default=None)
    ap.add_argument("--ocp", default=None, help="registered OCP pair name (default: dataset info)")
    ap.add_argument("--ocp-module", default=None, help="path.py that registers the OCP pair (YOUR code)")
    ap.add_argument("--cells", default=None, help="comma-separated cell ids (default all)")
    ap.add_argument("--out-dir", default=OUT_DEFAULT)
    ap.add_argument("--mode", default="auto", choices=["auto", "avg", "chg", "dis"])
    ap.add_argument("--fit-vlo", type=float, default=None)
    ap.add_argument("--fit-vhi", type=float, default=None)
    ap.add_argument("--n-starts", type=int, default=None)
    ap.add_argument("--jobs", type=int, default=max(1, min(6, (os.cpu_count() or 2) - 1)))
    ap.add_argument("--no-sensitivity", action="store_true")
    ap.add_argument("--no-figures", action="store_true")
    ap.add_argument("--fig-cells", default=None)
    args = ap.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    cells = args.cells.split(",") if args.cells else None
    t0 = time.time()
    log("loading", args.loader_spec or args.dataset)
    ds = dl.load_dataset(args.loader_spec or args.dataset, args.data_dir, cells)
    info = ds["info"]
    ocp_name = args.ocp or info["ocp"]
    ocp = dp.ensure_ocp(ocp_name, args.ocp_module)
    cfg = dc.FitConfig(vmin=info["vmin"], vmax=info["vmax"])
    if args.fit_vlo is not None:
        cfg.fit_vlo = args.fit_vlo
    if args.fit_vhi is not None:
        cfg.fit_vhi = args.fit_vhi
    if args.n_starts is not None:
        cfg.n_starts = args.n_starts
    meta = ds["meta"]
    curves = ds["curves"]
    log("cells", curves["cell"].nunique(), "rows", len(curves))

    log("main fit")
    rows = dp.fit_all(curves, ocp_name, cfg, args.mode, args.jobs, args.ocp_module, log)
    df = dp.assemble(rows, ocp, cfg, meta, "first_avg", variant="main")
    df_out = order_columns(df)
    for c in ("soh", "LLI", "LAM_PE", "LAM_NE"):
        pass
    p = os.path.join(args.out_dir, "D1_dva.csv")
    # attach T_group for convenience (extra column)
    if meta is not None and "T_group" in meta.columns:
        df_out = df_out.merge(meta[["cell", "T_group"]], on="cell", how="left")
    order_columns(df_out).to_csv(p, index=False, float_format="%.6g")
    log("wrote", p, df_out.shape)

    proto_cmp = None
    sens_notes = ""
    if not args.no_sensitivity:
        sens = []
        # (a) charge-only fits, reference = BOL charge fit (what the prototype did; for H cells = the BOL charge-only reference)
        log("sensitivity a: charge-only, ref = BOL")
        rows_c = dp.fit_all(curves, ocp_name, cfg, "chg", args.jobs, args.ocp_module, log)
        df_c = dp.assemble(rows_c, ocp, cfg, meta, "bol", variant="chg_bolref")
        sens.append(df_c)
        # (b) window extended to the full cycler window lower edge
        cfg_b = dc.FitConfig(**{**cfg.__dict__, "fit_vlo": cfg.vmin})
        log("sensitivity b: fit window lower edge = vmin")
        rows_b = dp.fit_all(curves, ocp_name, cfg_b, args.mode, args.jobs, args.ocp_module, log)
        df_b = dp.assemble(rows_b, ocp, cfg_b, meta, "first_avg", variant=f"avg_window_{cfg_b.fit_vlo:g}")
        sens.append(df_b)
        # (c) same-batch room-temperature BOL as the reference (absolute parameters of the mate's BOL averaged fit)
        if "room_mate" in meta.columns:
            over = {}
            for _, mrow in meta.iterrows():
                mate = mrow["room_mate"]
                if mate in rows:
                    ri = dp.choose_reference(rows[mate], "bol")
                    if ri is not None and rows[mate][ri]["kind"] == "avg" and mrow["cell"] != mate:
                        fr = rows[mate][ri]["fit"]
                        over[mrow["cell"]] = dict(Cp=fr.Cp, Cn=fr.Cn, nLi=fr.nLi, cap_meas=rows[mate][ri]["cap_dis"], label=f"mate{mate}")
            if over:
                rows_sub = {c: rows[c] for c in over}
                df_m = dp.assemble(rows_sub, ocp, cfg, meta, "first_avg", ref_override=over, variant="avg_roommate_bol")
                sens.append(df_m)
        # (d) reference = first averaged check-up after BOL for every cell (the fresh-cell BOL curve contains formation effects)
        df_d = dp.assemble(rows, ocp, cfg, meta, "second_avg", variant="avg_ref_after_bol")
        sens.append(df_d)
        S = pd.concat(sens, ignore_index=True)
        if meta is not None and "T_group" in meta.columns:
            S = S.merge(meta[["cell", "T_group"]], on="cell", how="left")
        keep = ["variant", "cell", "T_group", "checkup_idx", "ah", "mode_used", "soh", "LLI", "LAM_PE", "LAM_NE", "rmse_mV", "ref_checkup_idx",
                "loss_meas", "loss_implied", "loss_gap_pp", "pass_rmse", "pass_cap", "cap_evaluable", "is_ref"]
        S[[c for c in keep if c in S.columns]].to_csv(os.path.join(args.out_dir, "D1_sensitivity.csv"), index=False, float_format="%.6g")
        proto_cmp = compare_prototype(df, df_c) if args.dataset == "mohtat" else None
        # summary of sensitivities at the last check-up
        main_last = df[df["rmse_mV"].notna()].sort_values("ah").groupby("cell").tail(1).set_index("cell")
        lines = []
        for v, dv in pd.concat([S, df.assign(variant="main")], ignore_index=True).groupby("variant"):
            nr_ = dv[dv["rmse_mV"].notna() & ~dv["is_ref"].astype(bool)]
            ev_ = nr_[nr_["cap_evaluable"].astype(bool)]
            lines.append(f"- pass rates `{v}` (reference excluded): RMSE<10 mV {int(nr_['pass_rmse'].sum())}/{len(nr_)}; capacity within 1 pp {int(ev_['pass_cap'].sum())}/{len(ev_)}; median |gap| {ev_['loss_gap_pp'].abs().median():.2f} pp, median signed gap {ev_['loss_gap_pp'].median():+.2f} pp")
            if v == "main":
                continue
            dv = dv[dv["rmse_mV"].notna()].sort_values("ah").groupby("cell").tail(1).set_index("cell")
            common = dv.index.intersection(main_last.index)
            if not len(common):
                continue
            dd = {k: 100 * (dv.loc[common, k] - main_last.loc[common, k]) for k in ("LLI", "LAM_PE", "LAM_NE")}
            tgm = meta.set_index("cell")["T_group"] if "T_group" in meta.columns else pd.Series(index=common, dtype=object)
            lines.append(f"- `{v}` vs main at the last check-up (n={len(common)} cells): median diff LLI {dd['LLI'].median():+.1f}, LAM_PE {dd['LAM_PE'].median():+.1f}, LAM_NE {dd['LAM_NE'].median():+.1f} pp; "
                         f"max |diff| {dd['LLI'].abs().max():.1f}/{dd['LAM_PE'].abs().max():.1f}/{dd['LAM_NE'].abs().max():.1f} pp; RMSE median {dv.loc[common, 'rmse_mV'].median():.2f} mV.")
            for g in ("R", "C", "H"):
                cg = [c for c in common if tgm.get(c) == g]
